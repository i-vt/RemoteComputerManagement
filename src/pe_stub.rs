#[cfg(test)]
mod tests {
    #[test]
    fn stub_size_stable() {
        // Guards against accidental truncation when regenerating this file.
        assert_eq!(super::EXE_STUB_X64.len(), 1136);
    }

    #[test]
    fn stub_entry_prologue() {
        // 41 57 = push r15, then mov r15, rcx - first instructions of the
        // compiled `entry` (arg1 in rcx is the raw PE pointer).
        assert_eq!(super::EXE_STUB_X64[0], 0x41);
        assert_eq!(super::EXE_STUB_X64[1], 0x57);
    }

    #[test]
    fn stub_ends_with_ret_and_padding() {
        // The last real instruction before the alignment padding is `ret`;
        // the linker pads the section tail with 0x90/0xFF/0x00 fill.
        let s = super::EXE_STUB_X64;
        let ret_at = s.iter().rposition(|&b| b == 0xC3).unwrap();
        assert!(ret_at > s.len() - 64, "ret should be in the stub tail");
        assert!(s[ret_at + 1..].iter().all(|&b| matches!(b, 0x90 | 0x00 | 0xFF | 0xCC)));
    }
}
