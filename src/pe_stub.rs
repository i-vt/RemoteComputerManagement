// Precompiled x64 PE-loader stub (EXE/OEP variant of the sRDI stub),
// embedded as bytes.
//
// Source: tools/pe_stub.c (RCM original, same reflective-loading approach
// as monoxgas/sRDI which inspired it). Regenerate with tools/build_pe_stub.sh
// (requires x86_64-w64-mingw32-gcc + objcopy; both are in the Docker image).
//
// Difference from src/rdi_stub.rs: after mapping the image (sections, base
// relocations, imports via PEB walk + ROR13 hashing, TLS callbacks) the stub
// calls the PE's ORIGINAL ENTRY POINT (AddressOfEntryPoint) instead of
// DllMain / a hashed export, so it works for EXE payloads.
//
// Entry-point calling convention chosen:
//   entry(rcx = mapped image base, rdx = 1, r8 = NULL)
// which matches both the MinGW CRT EXE entry `void mainCRTStartup(void)`
// (arguments ignored) and a `DllMain(HMODULE, DLL_PROCESS_ATTACH, NULL)`.
//
// Invocation contract (Win64 fastcall), identical to the sRDI bootstrap in
// src/shellcode.rs:
//   rcx = pointer to the raw PE image (immediately after this stub)
//   edx = unused (bootstrap parity with the DLL stub)
//   r8 = pointer to user data blob
//   r9d = length of user data blob
//   [rsp+0x20]     = flags (bit0: wipe PE headers after load)
//   [rsp+0x28]     = base address of the shellcode itself
//
// The stub is 1136 bytes, position independent (no data references: kernel32
// is located by PEB walk and all APIs by ROR13 name hash), with `entry` at
// offset 0.

